    private addRedLetters(abbreviation: TRedLetterRules["abbreviation"], rules: Array<[TRedLetterRules["chapter"], TRedLetterRules["verse"], number, number?]>): void {
        rules.forEach(([chapter, verse, startWord, endWord]) => {
            const rule: TRedLetterRules = { 
                abbreviation: abbreviation, 
                chapter, 
                verse, 
                startWord 
            }

            if (endWord !== undefined) {
                rule.endWord = endWord
            }
            
            this.redLetterRules.push(rule)
        })
    }

    private addRedLettersRange(chapter: TRedLetterRules["chapter"], startVerse: number, endVerse: number, startWord: number = 1, endWord?: number): Array<[TRedLetterRules["chapter"], number, number, number?]> {
        const rules: Array<[TRedLetterRules["chapter"], number, number, number?]> = []

        for (let verse = startVerse; verse <= endVerse; verse++) {
            if (endWord !== undefined) {
                rules.push([chapter, verse, startWord, endWord])
            } else {
                rules.push([chapter, verse, startWord])
            }
        }
        
        return rules
    }

